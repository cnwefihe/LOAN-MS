export const DEFAULT_LOAN_POLICY_TITLE = "Staff loan policy";

export const DEFAULT_LOAN_POLICY_BODY = `## Eligibility
- Applicants must be confirmed members of staff, subject to verification by Human Resources.
- The purpose of the loan must be stated clearly on the application form.

## Procedure
- The application form must be completed in full, with the relevant supporting documents attached.
- Every loan is backed by a repayment agreement between the employee and the University. Total monthly deductions, including the loan repayment, must not exceed 33.3% of net pay on the payslip, so that the employee keeps reasonable living expenses.
- Every loan request must have two duly completed guarantors, except for products that need none, such as the Bereavement Loan.
- The loan is paid by direct credit to the employee's salary account.
- Approval is subject to the availability of funds.

## Eligibility and capacity of guarantors
- Any staff member may be chosen as a guarantor, provided they meet the conditions below.
- A guarantor must be a confirmed employee on the University payroll, with at least twelve months of continuous service and an employment period that runs beyond the final repayment date of the loan.
- A guarantor is not accepted where, if the borrower defaulted, their share of the monthly repayment would take their total monthly deductions and debt obligations above 30% of their net monthly salary.
- An employee may guarantee no more than two active loans, and only within the same 30% limit.

## Repayment
- The loan is repaid in equal monthly instalments deducted from salary, starting in the month after the loan is paid, over no more than 12 consecutive months.
- If employment ends, whether by the University or the employee, any outstanding balance is deducted in full from the final pay. Any amount still outstanding is payable at once by the employee or the guarantors.
- An employee may take another loan only after the existing loan is fully repaid.

## Additional protection
- A borrower must replace a guarantor who retires, resigns, dies, becomes insolvent, leaves the payroll or no longer meets the eligibility criteria.
- A guarantor receives written notice of the borrower's default and a short period to put it right before recovery begins.
- The University first applies the borrower's savings, deposits, benefits, insurance and authorised payroll deductions before turning to the guarantors.`;
